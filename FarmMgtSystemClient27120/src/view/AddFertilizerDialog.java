    private void btnSaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveActionPerformed
        // TODO add your handling code here:
        String fertilizerName = txtFertilizerName.getText().trim();
        String fertilizerType = txtFertilizerType.getText().trim();
        String description = txtFertilizerDescription.getText().trim();
        
        // Validation
        if (fertilizerName.isEmpty() || fertilizerType.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Fertilizer name and type are required!", "Validation Error", JOptionPane.ERROR_MESSAGE);
            return;
        }
        
        try {
            // Create fertilizer object
            Fertilizer fertilizer = new Fertilizer();
            fertilizer.setFertilizerName(fertilizerName);
            fertilizer.setFertilizerType(fertilizerType);
            fertilizer.setDescription(description.isEmpty() ? null : description);
            
            // Initialize fertilizer controller with proper error handling
            FertilizerController fertilizerController = null;
            try {
                fertilizerController = new FertilizerController();
            } catch (Exception ex) {
                JOptionPane.showMessageDialog(this, "Unable to connect to the server. Please check your connection and try again.", "Connection Error", JOptionPane.ERROR_MESSAGE);
                return;
            }
            
            if (fertilizerController == null) {
                JOptionPane.showMessageDialog(this, "Service unavailable. Please try again later.", "Service Error", JOptionPane.ERROR_MESSAGE);
                return;
            }
            
            // Save fertilizer
            Fertilizer savedFertilizer = fertilizerController.saveFertilizer(fertilizer);
            
            if (savedFertilizer != null) {
                // Associate fertilizer with crop if crop is provided
                if (crop != null && savedFertilizer.getFertilizerId() > 0) {
                    // Validate crop and its fertilizer set
                    if (crop.getFertilizerIds() != null) {
                        // Add fertilizer ID to crop's fertilizer set
                        crop.getFertilizerIds().add(savedFertilizer.getFertilizerId());
                        
                        // Initialize crop controller with proper error handling
                        CropController cropController = null;
                        try {
                            cropController = new CropController();
                        } catch (Exception ex) {
                            JOptionPane.showMessageDialog(this, "Fertilizer saved but unable to update crop. Please update crop manually.", "Warning", JOptionPane.WARNING_MESSAGE);
                        }
                        
                        if (cropController != null) {
                            try {
                                cropController.updateCropById(crop);
                            } catch (Exception ex) {
                                JOptionPane.showMessageDialog(this, "Fertilizer saved but unable to update crop. Please update crop manually.", "Warning", JOptionPane.WARNING_MESSAGE);
                            }
                        }
                    }
                }
                
                JOptionPane.showMessageDialog(this, "Fertilizer saved successfully!", "Success", JOptionPane.INFORMATION_MESSAGE);
                SessionManager sessionManager = SessionManager.getInstance();
                if (sessionManager != null) {
                    sessionManager.notifyDataChanged("fertilizer");
                }
                this.dispose();
            } else {
                JOptionPane.showMessageDialog(this, "Failed to save fertilizer. Please try again.", "Error", JOptionPane.ERROR_MESSAGE);
            }
        } catch (Exception ex) {
            JOptionPane.showMessageDialog(this, "An unexpected error occurred while saving fertilizer. Please try again.", "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnSaveActionPerformed

