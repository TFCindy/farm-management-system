    private void btnLoginActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnLoginActionPerformed
       // TODO add your handling code here:                                                                               
    // TODO add your handling code here:
    String nationalId = txtEmail.getText().trim();
    String password = new String(txtPassword.getPassword()).trim();

    // Validation
    if (nationalId.isEmpty() || password.isEmpty()) {
        showDualLanguageError("All fields are required!");
        return;
    }

    try {
        UserController userController = new UserController();
        User loggedUser = userController.login(nationalId, password);

        if (loggedUser != null) {
            // Store User object in session
            SessionManager session = SessionManager.getInstance();
            session.startSession(loggedUser);
            
            showDualLanguageWelcome(loggedUser.getFirstname(), loggedUser.getLastname());
            this.dispose();
            new DashboardFrame().setVisible(true);        
        } else {
            // Give a more specific, friendly message depending on identifier format
            if (nationalId.contains("@")) {
                showDualLanguageError("We couldn't sign you in. Please check your email and password. If you don't have an account, please sign up.");
            } else if (nationalId.matches("^(\\+?2507|07)\\d{8}$")) {
                showDualLanguageError("We couldn't sign you in. Please check your phone number and password.");
            } else {
                showDualLanguageError("We couldn't sign you in. Please check your National ID and password.");
            }
        }
    } catch (java.rmi.ConnectException e) {
        e.printStackTrace();
        showDualLanguageError("Can't reach the server right now. Please ensure the server is running and try again.");
    } catch (java.rmi.RemoteException e) {
        e.printStackTrace();
        // Produce a user-friendly message based on server exception content
        String friendly = getFriendlyMessageFromException(e, nationalId);
        showDualLanguageError(friendly);
        // Try a single retry for transient remote errors
        try {
            UserController retryController = new UserController();
            User loggedUser2 = retryController.login(nationalId, password);
            if (loggedUser2 != null) {
                SessionManager session = SessionManager.getInstance();
                session.startSession(loggedUser2);
                showDualLanguageWelcome(loggedUser2.getFirstname(), loggedUser2.getLastname());
                this.dispose();
                new DashboardFrame().setVisible(true);
                return;
            }
        } catch (Exception ex) {
            ex.printStackTrace();
        }
    } catch (Exception e) {
        e.printStackTrace();
        String friendly = getFriendlyMessageFromException(e, nationalId);
        showDualLanguageError("An error occurred during login. " + friendly);
    }                       
    }//GEN-LAST:event_btnLoginActionPerformed

    // Extract a friendly, sanitized message from exceptions (strip HTML/noisy wrappers)
    private String getFriendlyMessageFromException(Exception e, String identifier) {
        if (e == null) return "Please try again later.";
        String raw = e.getMessage();
        if (raw == null || raw.trim().isEmpty()) raw = e.toString();

        // Remove common RMI wrapper prefixes and HTML
        raw = raw.replaceAll("(?i)remoteexception occurred in server thread; nested exception is:", "");
        raw = raw.replaceAll("java\\.[^:]*:", "");
        raw = raw.replaceAll("<[^>]*>", "");
        raw = raw.replaceAll("\n", " ");
        raw = raw.trim();

        // Map server messages to friendly messages
        String lower = raw.toLowerCase();
        if (lower.contains("invalid credentials")) {
            // Give tailored hints depending on identifier
            if (identifier != null && identifier.contains("@")) {
                return "We couldn't sign you in. Your email or password may be incorrect. Use 'Forgot Password' if needed.";
            } else if (identifier != null && identifier.matches("^(\\+?2507|07)\\d{8}$")) {
                return "We couldn't sign you in. Your phone number or password may be incorrect.";
            } else {
                return "We couldn't sign you in. Your National ID or password may be incorrect.";
            }
        }

        if (lower.contains("user not found") || lower.contains("account exists") == false && lower.contains("not found")) {
            if (identifier != null && identifier.contains("@")) {
                return "No account found for that email. Please sign up first or check the email you entered.";
            } else {
                return "No account found with that identifier. Please sign up first or check your details.";
            }
        }

        if (lower.contains("invalid or expired otp")) {
            return "The OTP is invalid or has expired. Request a new OTP and try again.";
        }

        // For other cases, show a concise sanitized message
        if (raw.length() > 200) raw = raw.substring(0, 200) + "...";
        return raw;
    }

