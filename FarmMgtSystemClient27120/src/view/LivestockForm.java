    private boolean validateForm() {
        String animalType = txtAnimalType.getText().trim();
        String ageText = txtAge.getText().trim();
        String healthStatus = cmbHealthStatus.getSelectedItem().toString().trim();
        String quantityText = txtQuantity.getText().trim();

        if (animalType.isEmpty() || healthStatus.equals("Select Health Status") || ageText.isEmpty()
                || quantityText.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please fill all required fields!", "Validation Error",
                    JOptionPane.ERROR_MESSAGE);
            return false;
        }

        try {
            int age = Integer.parseInt(ageText);
            int quantity = Integer.parseInt(quantityText);

            if (age < 0 || age > 50) {
                JOptionPane.showMessageDialog(this, "Please enter a valid age (0-50)!", "Validation Error",
                        JOptionPane.ERROR_MESSAGE);
                return false;
            }

            if (quantity <= 0 || quantity > 1000) {
                JOptionPane.showMessageDialog(this, "Please enter a valid quantity (1-1000)!", "Validation Error",
                        JOptionPane.ERROR_MESSAGE);
                return false;
            }
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Age and Quantity must be numbers!", "Validation Error",
                    JOptionPane.ERROR_MESSAGE);
            return false;
        }

        return true;
    }

