    private void tblLivestockMouseClicked(java.awt.event.MouseEvent evt) {
        // Table row click event
        int row = tblLivestock.getSelectedRow();
        if (row >= 0) {
            try {
                // Reset any previous editing state
                if (isEditing) {
                    isEditing = false;
                    btnUpdate.setText("Update livestock");
                    setFieldsEditable(false);
                }

                int animalId = Integer.parseInt(tblLivestock.getValueAt(row, 0).toString());
                String animalType = tblLivestock.getValueAt(row, 1).toString();
                int age = Integer.parseInt(tblLivestock.getValueAt(row, 2).toString());
                String breed = tblLivestock.getValueAt(row, 3).toString();
                String healthStatus = tblLivestock.getValueAt(row, 4).toString();
                int quantity = Integer.parseInt(tblLivestock.getValueAt(row, 5).toString());

                Livestock livestock = new Livestock();
                livestock.setAnimalId(animalId);
                livestock.setAnimalType(animalType);
                livestock.setBreed(breed);
                livestock.setAge(age);
                livestock.setHealthStatus(healthStatus);
                livestock.setQuantity(quantity);

                populateForm(livestock);
                setFieldsEditable(false);
                setSelectedAnimalId(animalId); // Use method to set

                JOptionPane.showMessageDialog(this,
                        "Record loaded. Click Update to modify or Delete to remove.",
                        "Record Selected",
                        JOptionPane.INFORMATION_MESSAGE);

            } catch (Exception e) {
                JOptionPane.showMessageDialog(this, "Error selecting record: " + e.getMessage(), "Selection Error",
                        JOptionPane.ERROR_MESSAGE);
                resetSelectedAnimalId(); // Use method to reset on error
            }
        }
    }

