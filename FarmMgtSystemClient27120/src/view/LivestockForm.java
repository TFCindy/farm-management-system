    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
        // TODO add your handling code here:
       // GEN-FIRST:event_jButton4ActionPerformed
        // TODO add your handling code here:
        // Delete Livestock Button
        if (!isAnimalSelected()) {
            JOptionPane.showMessageDialog(this, "Please select a livestock record to delete.", "No Selection",
                    JOptionPane.WARNING_MESSAGE);
            return;
        }

        // Get the animal type for confirmation message
        String animalType = txtAnimalType.getText().trim();
        String confirmationMessage = "Are you sure you want to delete the livestock record for: " + animalType + "?";

        int confirm = JOptionPane.showConfirmDialog(this,
                confirmationMessage,
                "Confirm Deletion",
                JOptionPane.YES_NO_OPTION,
                JOptionPane.WARNING_MESSAGE);

        if (confirm == JOptionPane.YES_OPTION) {
            try {
                LivestockController livestockController = new LivestockController();
                boolean result = livestockController.deleteLivestockById(getSelectedAnimalId(),
                        SessionManager.getInstance().getCurrentUserId());

                if (result) {
                    JOptionPane.showMessageDialog(this, "Livestock deleted successfully!");
                    clearForm();
                    // Only refresh table if it has data (user clicked Show All)
                    DefaultTableModel model = (DefaultTableModel) tblLivestock.getModel();
                    if (model.getRowCount() > 0) {
                        loadAllLivestock();
                    }
                    resetSelectedAnimalId(); // Use method to reset
                    // Fields should be editable after clearing
                    setFieldsEditable(true);

                    // Reset update button text if it was in edit mode
                    if (isEditing) {
                        isEditing = false;
                        btnUpdate.setText("Update livestock");
                    }
                    try {
                        SessionManager.getInstance().notifyDataChanged("livestock");
                    } catch (Exception ignored) {
                    }
                } else {
                    JOptionPane.showMessageDialog(this,
                            "Failed to delete livestock. Record may not exist or you don't have permission.", "Error",
                            JOptionPane.ERROR_MESSAGE);
                }
            } catch (Exception e) {
                JOptionPane.showMessageDialog(this, "Error: " + e.getMessage(), "Database Error",
                        JOptionPane.ERROR_MESSAGE);
                e.printStackTrace();
            }
        }
    }//GEN-LAST:event_btnDeleteActionPerformed

