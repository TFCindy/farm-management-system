    private void btnSaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveActionPerformed
        // TODO add your handling code here:
        if (employee == null) {
            JOptionPane.showMessageDialog(this, "No employee selected. Please select an employee first.", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }
        
        // Validation
        String contractTypeStr = jComboBox1.getSelectedItem().toString().trim();
        Date startDate = jDateChooser1.getDate();
        Date endDate = jDateChooser2.getDate();
        String termsAndCond = txtTermsAndCond.getText().trim();
        String bankName = txtBankName.getText().trim();
        String bankAccNumber = txtBankAccNumber.getText().trim();
        
        if (contractTypeStr.isEmpty() || startDate == null || endDate == null) {
            JOptionPane.showMessageDialog(this, "Contract type, start date, and end date are required!", "Validation Error", JOptionPane.ERROR_MESSAGE);
            return;
        }
        
        if (endDate.before(startDate)) {
            JOptionPane.showMessageDialog(this, "End date cannot be before start date!", "Validation Error", JOptionPane.ERROR_MESSAGE);
            return;
        }
        
        try {
            // Create contract object
            EmployeeContract contract = new EmployeeContract();
            contract.setEmployee(employee);
            
            // Convert contract type string to enum
            EmployeeContract.ContractType contractType;
            try {
                contractType = EmployeeContract.ContractType.valueOf(contractTypeStr.toUpperCase());
            } catch (IllegalArgumentException e) {
                JOptionPane.showMessageDialog(this, "Invalid contract type!", "Validation Error", JOptionPane.ERROR_MESSAGE);
                return;
            }
            
            contract.setContractType(contractType);
            contract.setStartDate(startDate);
            contract.setEndDate(endDate);
            contract.setTermsAndConditions(termsAndCond.isEmpty() ? null : termsAndCond);
            contract.setHealthInsurance(checkBoxHealthInsurance.isSelected());
            contract.setHousingAllowance(checkBoxHousingAllowance.isSelected());
            contract.setTransportAllowance(checkBoxTransportAllowance.isSelected());
            contract.setBonusEligibility(checkBoxHouseEligibility.isSelected());
            contract.setBankName(bankName.isEmpty() ? null : bankName);
            contract.setBankAccountNumber(bankAccNumber.isEmpty() ? null : bankAccNumber);
            
            // Save via controller
            EmployeeContractController contractController = new EmployeeContractController();
            EmployeeContract savedContract = contractController.saveContract(contract);
            
            if (savedContract != null) {
                JOptionPane.showMessageDialog(this, "Contract saved successfully!", "Success", JOptionPane.INFORMATION_MESSAGE);
                SessionManager.getInstance().notifyDataChanged("contract");
                this.dispose();
            } else {
                JOptionPane.showMessageDialog(this, "Failed to save contract.", "Error", JOptionPane.ERROR_MESSAGE);
            }
        } catch (Exception ex) {
            JOptionPane.showMessageDialog(this, "An unexpected error occurred while saving contract. Please try again.", "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnSaveActionPerformed

