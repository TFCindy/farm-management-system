    private void btnSignupActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSignupActionPerformed
        // TODO add your handling code here:                                                                      
    String nationalId = txtFarmerID.getText().trim();
    String firstname = txtFirstname.getText().trim();
    String lastname = txtLastname.getText().trim();
    String password = new String(txtPassword.getPassword()).trim();
    String district = cmbDistrict.getSelectedItem().toString().trim();
    String email = txtEmail.getText().trim(); // Added email field
    String phoneNumber = txtPhoneNumber.getText().trim(); // Added phone number field

    // 1️⃣ Validation - Check all fields are filled
    if(nationalId.isEmpty() || firstname.isEmpty() || lastname.isEmpty() || 
       password.isEmpty() || district.isEmpty() || district.equals("Select District") ||
       email.isEmpty() || phoneNumber.isEmpty()) {
        JOptionPane.showMessageDialog(this, "All fields are required!", "Validation Error", JOptionPane.ERROR_MESSAGE);
        return;
    }

    // Validate National ID (Rwandan ID format)
    if(!isValidRwandanNationalId(nationalId)) {
        JOptionPane.showMessageDialog(this, "National ID must be exactly 16 digits starting with 1, 2, or 3!", 
                                      "Validation Error", JOptionPane.ERROR_MESSAGE);
        return;
    }

    // Validate password strength
    if(!isValidPassword(password)) {
        JOptionPane.showMessageDialog(this, "Password must be at least 8 characters with uppercase, lowercase, number & symbol!", 
                                      "Validation Error", JOptionPane.ERROR_MESSAGE);
        return;
    }

    // Validate email format
    if(!isValidEmail(email)) {
        JOptionPane.showMessageDialog(this, "Please enter a valid email address!", 
                                      "Validation Error", JOptionPane.ERROR_MESSAGE);
        return;
    }

    // Validate phone number (Rwandan format)
    if(!isValidRwandanPhoneNumber(phoneNumber)) {
        JOptionPane.showMessageDialog(this, "Phone number must be 10 digits (07XXXXXXXX) or 12 digits (+2507XXXXXXXX)!", 
                                      "Validation Error", JOptionPane.ERROR_MESSAGE);
        return;
    }

    // Validate district selection
    if(district.equals("Select District") || district.equals("--Select--") || district.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Please select a valid district!", "Validation Error", JOptionPane.ERROR_MESSAGE);
        return;
    }

    try {
        // Create user object
        User newUser = new User();
        newUser.setNationalId(nationalId);
        newUser.setFirstname(firstname);
        newUser.setLastname(lastname);
        newUser.setPassword(password);
        newUser.setDistrict(district);
        newUser.setEmail(email);
        newUser.setPhoneNumber(phoneNumber);

        // Use controller to save user via RMI
        UserController userController = new UserController();
        User savedUser = userController.saveUser(newUser);
        
        if(savedUser != null) {
            JOptionPane.showMessageDialog(this, "Signup successful! An OTP was sent to your email. Please verify it to continue.", "Success", JOptionPane.INFORMATION_MESSAGE);
            // Open OTP verification dialog
            OtpVerificationDialog otpDialog = new OtpVerificationDialog(this, true, email);
            otpDialog.setVisible(true);
            
            User verifiedUser = otpDialog.getVerifiedUser();
            if (verifiedUser != null) {
                // OTP verified successfully, user is logged in
                this.dispose();
                new DashboardFrame().setVisible(true);
            } else {
                // OTP verification cancelled or failed
                JOptionPane.showMessageDialog(this, "OTP verification required. Please login using password or verify OTP.", "Notice", JOptionPane.INFORMATION_MESSAGE);
                this.dispose();
                new LoginForm().setVisible(true);
            }
        } else {
            JOptionPane.showMessageDialog(this, "Signup failed. User may already exist.", "Error", JOptionPane.ERROR_MESSAGE);
        }

    } catch(Exception e) {
        JOptionPane.showMessageDialog(this, "An unexpected error occurred during signup. Please try again.", "Error", JOptionPane.ERROR_MESSAGE);
    }
    }//GEN-LAST:event_btnSignupActionPerformed

    
  private boolean isValidEmail(String email) {
    // Basic email regex pattern
    String emailRegex = "^[A-Za-z0-9+_.-]+@[A-Za-z0-9.-]+\\.[A-Za-z]{2,}$";
    return email.matches(emailRegex);
}

private boolean isValidRwandanPhoneNumber(String phoneNumber) {
    // Remove any spaces or dashes
    phoneNumber = phoneNumber.replaceAll("[\\s-]+", "");
    
    // Check if it's all digits (except possible + prefix)
    if(phoneNumber.startsWith("+")) {
        // Check if after + it's all digits
        String digits = phoneNumber.substring(1);
        if(!digits.matches("\\d+")) {
            return false;
        }
    } else {
        // Check if it's all digits
        if(!phoneNumber.matches("\\d+")) {
            return false;
        }
    }
    
    // Check for valid Rwandan phone formats
    // Format 1: 07XXXXXXXX (10 digits)
    if(phoneNumber.length() == 10 && phoneNumber.startsWith("07")) {
        return true;
    }
    
    // Format 2: +2507XXXXXXXX (12 digits with +)
    if(phoneNumber.length() == 12 && phoneNumber.startsWith("+2507")) {
        return true;
    }
    
    // Format 3: 2507XXXXXXXX (11 digits without + but with 250)
    if(phoneNumber.length() == 11 && phoneNumber.startsWith("2507")) {
        return true;
    }
    
    return false;
}

// Your existing validation methods (keep these)
private boolean isValidRwandanNationalId(String nationalId) {
    if(nationalId.length() != 16) {
        return false;
    }
    
    // Check if all characters are digits
    if(!nationalId.matches("\\d+")) {
        return false;
    }
    
    // Check if starts with 1, 2, or 3
    char firstDigit = nationalId.charAt(0);
    return firstDigit == '1' || firstDigit == '2' || firstDigit == '3';
}

private boolean isValidPassword(String password) {
    // Check minimum length
    if(password.length() < 8) {
        return false;
    }
    
    // Check for at least one uppercase letter
    if(!password.matches(".*[A-Z].*")) {
        return false;
    }
    
    // Check for at least one lowercase letter
    if(!password.matches(".*[a-z].*")) {
        return false;
    }
    
    // Check for at least one digit
    if(!password.matches(".*\\d.*")) {
        return false;
    }
    
    // Check for at least one special character
    if(!password.matches(".*[!@#$%^&*(),.?\":{}|<>].*")) {
        return false;
    }
    
    return true;
}
