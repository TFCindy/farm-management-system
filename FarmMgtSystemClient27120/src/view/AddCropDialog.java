    private void refreshDashboard() {
        // Use SessionManager to notify data change instead of directly referencing
        // DashboardFrame.
        // This avoids compile-time dependency issues and leverages the listener
        // pattern.
        try {
            SessionManager.getInstance().notifyDataChanged("crop");
        } catch (Exception e) {
            System.err.println("Error notifying dashboard refresh: " + e.getMessage());
        }
    }

    private boolean isFormNotEmpty() {
        return !txtCropName.getText().trim().isEmpty() ||
                !txtExpectedYield.getText().trim().isEmpty() ||
                jPlantingDate.getDate() != null ||
                jHarvestDate.getDate() != null ||
                (cmbStatus.getSelectedItem() != null
                        && !cmbStatus.getSelectedItem().toString().equals("Select Status"));
    }

