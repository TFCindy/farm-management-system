    private void btnSaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveActionPerformed
        // TODO add your handling code here:
       // GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:
        // TODO add your handling code here:

        // Get form data - JDateChooser returns java.util.Date directly
        String cropName = txtCropName.getText().trim();
        Date plantingDate = jPlantingDate.getDate(); // Direct java.util.Date from JDateChooser
        Date harvestDate = jHarvestDate.getDate(); // Direct java.util.Date from JDateChooser
        String yieldText = txtExpectedYield.getText().trim();
        String status = cmbStatus.getSelectedItem().toString().trim();

        // Validation - All fields are required
        if (cropName.isEmpty() ||
                plantingDate == null ||
                harvestDate == null ||
                yieldText.isEmpty() ||
                status.equals("Select Status")) {

            showDualLanguageError("All fields are required!");
            return;
        }

        // Validate dates - harvest date cannot be before planting date
        if (harvestDate.before(plantingDate)) {
            showDualLanguageError("Harvest date cannot be before planting date!");
            return;
        }

        // Validate expected yield is a positive number
        double expectedYield;
        try {
            expectedYield = Double.parseDouble(yieldText);
            if (expectedYield <= 0) {
                showDualLanguageError("Expected yield must be a positive number!");
                return;
            }
        } catch (NumberFormatException e) {
            showDualLanguageError("Expected yield must be a valid number!");
            return;
        }

        // Validate dates are not in the future (optional)
        Date currentDate = new Date();
        if (plantingDate.after(currentDate)) {
            showDualLanguageError("Planting date cannot be in the future!");
            return;
        }

        try {
            // Check if user is logged in
            SessionManager session = SessionManager.getInstance();
            if (!session.isLoggedIn()) {
                showDualLanguageError("Please login to add crop.");
                this.dispose();
                return;
            }

            // Create crop object - NO CONVERSION NEEDED!
            Crop crop = new Crop();
            crop.setNationalId(session.getCurrentUserId());
            crop.setCropName(cropName);
            crop.setPlantingDate(plantingDate); // Direct java.util.Date
            crop.setHarvestDate(harvestDate); // Direct java.util.Date
            crop.setExpectedYield(expectedYield);
            crop.setStatus(status);

            // Save to database via controller
            CropController cropController = new CropController();
            int result = cropController.createCrop(crop);

            if (result > 0) {
                // Notify SessionManager that data changed
                SessionManager.getInstance().notifyDataChanged("crop");
                
                // Dispose immediately after save
                this.dispose();

            } else {
                showDualLanguageError("Failed to add crop. Please try again.");
            }

        } catch (java.rmi.ConnectException e) {
            showDualLanguageError("Unable to connect to server. Please ensure the server is running and try again.");
        } catch (java.rmi.RemoteException e) {
            String msg = e.getMessage();
            if (msg != null && !msg.trim().isEmpty()) {
                showDualLanguageError(msg);
            } else {
                showDualLanguageError("Connection error. Please check your network connection and try again.");
            }
        } catch (Exception e) {
            showDualLanguageError("An error occurred while adding crop. Please try again.");
        }
    }//GEN-LAST:event_btnSaveActionPerformed

