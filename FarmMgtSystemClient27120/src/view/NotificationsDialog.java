    private void loadNotifications() {
    // Small delay to ensure UI is fully built
    SwingUtilities.invokeLater(() -> {
        String nationalId = SessionManager.getInstance().getCurrentUserId();
        
        // Use the class field contentPanel directly
        if (contentPanel == null) {
            System.out.println("Content panel is null - cannot load notifications");
            return;
        }
        
        contentPanel.removeAll();
            
        List<String> allNotifications = new ArrayList<>();
        
        // Get crop notifications
        List<String> cropNotifications = getCropNotifications(nationalId);
        allNotifications.addAll(cropNotifications);
        
        // Get livestock notifications
        List<String> livestockNotifications = getLivestockNotifications(nationalId);
        allNotifications.addAll(livestockNotifications);
        
        // Get employee contract notifications
        List<String> employeeNotifications = getEmployeeContractNotifications(nationalId);
        allNotifications.addAll(employeeNotifications);
        
        // Display notifications
        if (allNotifications.isEmpty()) {
            JLabel noNotificationsLabel = new JLabel(TranslationManager.getTranslation("No_notifications_available"));
            noNotificationsLabel.setFont(new Font("SansSerif", Font.PLAIN, 14));
            noNotificationsLabel.setForeground(Color.GRAY);
            noNotificationsLabel.setAlignmentX(Component.LEFT_ALIGNMENT);
            noNotificationsLabel.setBorder(new EmptyBorder(10, 0, 10, 0));
            contentPanel.add(noNotificationsLabel);
        } else {
            // Group by category
            displayNotificationGroup(TranslationManager.getTranslation("Crops"), cropNotifications, contentPanel);
            displayNotificationGroup(TranslationManager.getTranslation("Livestock"), livestockNotifications, contentPanel);
            displayNotificationGroup(TranslationManager.getTranslation("Employee Contracts"), employeeNotifications, contentPanel);
        }
        
        contentPanel.revalidate();
        contentPanel.repaint();
    });
}
    
    private void displayNotificationGroup(String category, List<String> notifications, JPanel parent) {
        if (notifications.isEmpty()) return;
        
        // Category header
        JLabel categoryLabel = new JLabel(category);
        categoryLabel.setFont(new Font("SansSerif", Font.BOLD, 16));
        categoryLabel.setForeground(new Color(0, 153, 153));
        categoryLabel.setAlignmentX(Component.LEFT_ALIGNMENT);
        categoryLabel.setBorder(new EmptyBorder(10, 0, 5, 0));
        parent.add(categoryLabel);
        
        // Add notifications
        for (String notification : notifications) {
            JPanel notificationPanel = new JPanel(new BorderLayout());
            notificationPanel.setBackground(Color.WHITE);
            notificationPanel.setAlignmentX(Component.LEFT_ALIGNMENT);
            notificationPanel.setBorder(BorderFactory.createCompoundBorder(
                BorderFactory.createMatteBorder(0, 0, 1, 0, new Color(220, 220, 220)),
                new EmptyBorder(8, 5, 8, 5)
            ));
            
            JLabel notificationLabel = new JLabel("<html>" + notification + "</html>");
            notificationLabel.setFont(new Font("SansSerif", Font.PLAIN, 13));
            notificationLabel.setForeground(Color.DARK_GRAY);
            
            notificationPanel.add(notificationLabel, BorderLayout.CENTER);
            parent.add(notificationPanel);
        }
    }
    
    private List<String> getCropNotifications(String nationalId) {
    List<String> notifications = new ArrayList<>();
    try {
        CropController cropController = new CropController();
        List<Crop> crops = cropController.findCropsByUser(nationalId);
        Date currentDate = new Date();
        
        for (Crop crop : crops) {
            String cropName = crop.getCropName() != null ? crop.getCropName() : "Unknown Crop";
            
            // Check harvest date (7 days or less)
            if (crop.getHarvestDate() != null) {
                long diff = crop.getHarvestDate().getTime() - currentDate.getTime();
                long daysLeft = diff / (1000 * 60 * 60 * 24);
                
                if (daysLeft >= 0 && daysLeft <= 7) {
                    String message = createDualLanguageMessage(
                        "Crop " + cropName + " is expected to be harvested soon (" + daysLeft + " days left).",
                        "Igihingwa " + cropName + " gitegerejwe gusarurwa vuba (" + daysLeft + " iminsi isigaye)."
                    );
                    notifications.add(message);
                }
            }
            
            // Check planting date (3 days or less)
            if (crop.getPlantingDate() != null) {
                long diff = crop.getPlantingDate().getTime() - currentDate.getTime();
                long daysLeft = diff / (1000 * 60 * 60 * 24);
                
                if (daysLeft >= 0 && daysLeft <= 3) {
                    String message = createDualLanguageMessage(
                        "Crop " + cropName + " planting date is approaching (" + daysLeft + " days left).",
                        "Itariki yo guhinga " + cropName + " iregereje (" + daysLeft + " iminsi isigaye)."
                    );
                    notifications.add(message);
                }
            }
        }
    } catch (Exception e) {
        System.err.println("Error loading crop notifications: " + e.getMessage());
    }
    
    return notifications;
}

private List<String> getLivestockNotifications(String nationalId) {
    List<String> notifications = new ArrayList<>();
    try {
        LivestockController livestockController = new LivestockController();
        List<Livestock> livestockList = livestockController.findLivestockByUser(nationalId);
        
        for (Livestock livestock : livestockList) {
            // Check for sick animals
            if ("sick".equalsIgnoreCase(livestock.getHealthStatus())) {
                String animalType = livestock.getAnimalType() != null ? livestock.getAnimalType() : "Unknown Animal";
                String message = createDualLanguageMessage(
                    "Livestock " + animalType + " is marked as sick. Immediate attention required.",
                    "Itungo " + animalType + " rirwaye. Rikeneye kwitabwaho byihutirwa."
                );
                notifications.add(message);
            }
        }
    } catch (Exception e) {
        System.err.println("Error loading livestock notifications: " + e.getMessage());
    }
    
    return notifications;
}

private List<String> getEmployeeContractNotifications(String nationalId) {
    List<String> notifications = new ArrayList<>();
    try {
        // Use EmployeeContractController to get contracts
        controller.EmployeeContractController contractController = new controller.EmployeeContractController();
        List<model.EmployeeContract> contracts = contractController.getContractsByNationalId(nationalId);
        
        Date currentDate = new Date();
        Calendar cal = Calendar.getInstance();
        cal.setTime(currentDate);
        cal.add(Calendar.DAY_OF_MONTH, 7); // 7 days from now
        Date sevenDaysLater = cal.getTime();
        
        for (model.EmployeeContract contract : contracts) {
            if (contract.getEndDate() != null) {
                Date endDate = contract.getEndDate();
                
                // Check if contract ends within 7 days
                if (endDate.before(sevenDaysLater) && !endDate.before(currentDate)) {
                    long diff = endDate.getTime() - currentDate.getTime();
                    long daysLeft = diff / (1000 * 60 * 60 * 24);
                    
                    String employeeName = "Employee";
if (contract.getEmployee() != null) {
    employeeName = contract.getEmployee().getName();
}

                    
                    String message = createDualLanguageMessage(
                        "Contract for " + employeeName + " expires in " + daysLeft + " day" + (daysLeft != 1 ? "s" : "") + ".",
                        "Amasezerano ya " + employeeName + " ararangira mu " + daysLeft + " umunsi" + (daysLeft != 1 ? "s" : "") + "."
                    );
                    notifications.add(message);
                }
            }
        }
    } catch (Exception e) {
        System.err.println("Error loading employee contract notifications: " + e.getMessage());
    }
    
    return notifications;
}

// Helper method to create dual-language HTML message
private String createDualLanguageMessage(String english, String kinyarwanda) {
    return "<html><div>" + english + "</div><div style='font-size: 11px; font-style: italic; color: #666; margin-top: 2px;'>" + kinyarwanda + "</div></html>";
}
