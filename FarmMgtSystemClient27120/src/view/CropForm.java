    private void tblCropsMouseClicked(java.awt.event.MouseEvent evt) {
        int row = tblCrops.getSelectedRow();
        if (row >= 0) {
            try {
                // Reset any previous editing state
                if (isEditing) {
                    isEditing = false;
                    btnUpdate.setText("Update Crop");
                    setFieldsEditable(false);
                }

                int cropId = Integer.parseInt(tableModel.getValueAt(row, 0).toString());
                String cropName = tableModel.getValueAt(row, 1).toString();

                // FIXED: Use setDate() for JDateChooser instead of setText()
                Object plantingDateObj = tableModel.getValueAt(row, 2);
                Object harvestDateObj = tableModel.getValueAt(row, 3);

                // Convert to java.util.Date for JDateChooser
                java.util.Date plantingDate = null;
                java.util.Date harvestDate = null;

                if (plantingDateObj instanceof java.util.Date) {
                    plantingDate = (java.util.Date) plantingDateObj;
                } else if (plantingDateObj != null) {
                    // If it's stored as string or other format, convert it
                    String dateStr = plantingDateObj.toString();
                    if (!dateStr.isEmpty()) {
                        try {
                            plantingDate = java.sql.Date.valueOf(dateStr);
                        } catch (Exception e) {
                            // Try other date parsing if needed
                            System.out.println("Error parsing planting date: " + dateStr);
                        }
                    }
                }

                if (harvestDateObj instanceof java.util.Date) {
                    harvestDate = (java.util.Date) harvestDateObj;
                } else if (harvestDateObj != null) {
                    // If it's stored as string or other format, convert it
                    String dateStr = harvestDateObj.toString();
                    if (!dateStr.isEmpty()) {
                        try {
                            harvestDate = java.sql.Date.valueOf(dateStr);
                        } catch (Exception e) {
                            // Try other date parsing if needed
                            System.out.println("Error parsing harvest date: " + dateStr);
                        }
                    }
                }

                double expectedYield = Double.parseDouble(tableModel.getValueAt(row, 4).toString());
                String status = tableModel.getValueAt(row, 5).toString();

                // FIXED: Use setDate() for JDateChooser
                txtCropName.setText(cropName);
                jPlantingDate.setDate(plantingDate); // This is correct for JDateChooser
                jHarvestDate.setDate(harvestDate); // This is correct for JDateChooser
                txtExpectedYield.setText(String.valueOf(expectedYield));
                cmbStatus.setSelectedItem(status);

                setFieldsEditable(false);
                setSelectedCropId(cropId);

                JOptionPane.showMessageDialog(this,
                        "Record loaded. Click Update to modify or Delete to remove.",
                        "Record Selected",
                        JOptionPane.INFORMATION_MESSAGE);

            } catch (Exception e) {
                JOptionPane.showMessageDialog(this, "Error selecting crop: " + e.getMessage(), "Selection Error",
                        JOptionPane.ERROR_MESSAGE);
                e.printStackTrace();
                resetSelectedCropId();
            }
        }
    }

