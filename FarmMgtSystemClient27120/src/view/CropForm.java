    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        // TODO add your handling code here:
        if (!isCropSelected()) {
            JOptionPane.showMessageDialog(this, "Please select a crop first to add fertilizer details.", "No Selection", JOptionPane.WARNING_MESSAGE);
            return;
        }
        
        try {
            // Get selected crop
            CropController cropController = new CropController();
            Crop crop = new Crop();
            crop.setCropId(getSelectedCropId());
            Crop selectedCrop = cropController.searchCropById(crop);
            
            if (selectedCrop == null) {
                JOptionPane.showMessageDialog(this, "Crop not found.", "Error", JOptionPane.ERROR_MESSAGE);
                return;
            }
            
            // Open fertilizer dialog
            AddFertilizerDialog fertilizerDialog = new AddFertilizerDialog(this, true, selectedCrop);
            fertilizerDialog.setVisible(true);
            
            // Refresh if fertilizer was added
            if (tableModel.getRowCount() > 0) {
                loadAllCrops();
            }
        } catch (Exception ex) {
            JOptionPane.showMessageDialog(this, "Error opening fertilizer dialog: " + ex.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
            ex.printStackTrace();
        }
    }//GEN-LAST:event_jButton2ActionPerformed

    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed
        // TODO add your handling code here:// GEN-FIRST:event_btnUpdateActionPerformed
        // TODO add your handling code here:
        if (!isEditing) {
            // Start editing mode
            if (!isCropSelected()) {
                JOptionPane.showMessageDialog(this, "Please select a crop to update.", "No Selection",
                        JOptionPane.WARNING_MESSAGE);
                return;
            }

            setFieldsEditable(true);
            isEditing = true;
            btnUpdate.setText("Save Changes");
            JOptionPane.showMessageDialog(this, "You can now edit the fields. Click 'Save Changes' when done.");
        } else {
            // Save changes
            if (validateForm()) {
                try {
                    Crop crop = new Crop();
                    crop.setCropId(getSelectedCropId());
                    crop.setNationalId(SessionManager.getInstance().getCurrentUserId());
                    crop.setCropName(txtCropName.getText().trim());
                    crop.setPlantingDate(jPlantingDate.getDate());
                    crop.setHarvestDate(jHarvestDate.getDate());
                    crop.setExpectedYield(Double.parseDouble(txtExpectedYield.getText().trim()));
                    crop.setStatus(cmbStatus.getSelectedItem().toString());

                    CropController cropController = new CropController();
                    int result = cropController.updateCropById(crop);

                    if (result > 0) {
                        JOptionPane.showMessageDialog(this, "Crop updated successfully!");
                        isEditing = false;
                        btnUpdate.setText("Update Crop");

                        // AUTO-CLEAR FORM
                        clearForm();
                        // Only refresh table if it has data (user clicked Show All)
                        if (tableModel.getRowCount() > 0) {
                            loadAllCrops();
                        }
                        resetSelectedCropId();
                        // Fields should be editable after clearing
                        setFieldsEditable(true);

                        // Notify SessionManager that data changed
                        SessionManager.getInstance().notifyDataChanged("crop");
                    } else {
                        JOptionPane.showMessageDialog(this, "Failed to update crop.", "Error",
                                JOptionPane.ERROR_MESSAGE);
                    }
                } catch (Exception e) {
                    JOptionPane.showMessageDialog(this, "Error: " + e.getMessage(), "Database Error",
                            JOptionPane.ERROR_MESSAGE);
                    e.printStackTrace();
                }
            }
        }
    }//GEN-LAST:event_btnUpdateActionPerformed

