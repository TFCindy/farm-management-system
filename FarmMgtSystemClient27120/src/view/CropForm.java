    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
        // TODO add your handling code here:
// GEN-FIRST:event_btnDeleteActionPerformed
        // TODO add your handling code here:
        if (!isCropSelected()) {
            JOptionPane.showMessageDialog(this, "Please select a crop to delete.", "No Selection",
                    JOptionPane.WARNING_MESSAGE);
            return;
        }

        String cropName = txtCropName.getText().trim();
        int confirm = JOptionPane.showConfirmDialog(this,
                "Are you sure you want to delete crop: " + cropName + "?",
                "Confirm Deletion",
                JOptionPane.YES_NO_OPTION,
                JOptionPane.WARNING_MESSAGE);

        if (confirm == JOptionPane.YES_OPTION) {
            try {
                CropController cropController = new CropController();
                boolean result = cropController.deleteCropById(getSelectedCropId(), SessionManager.getInstance().getCurrentUserId());

                if (result) {
                    JOptionPane.showMessageDialog(this, "Crop deleted successfully!");

                    // AUTO-CLEAR FORM
                    clearForm();
                    // Only refresh table if it has data (user clicked Show All)
                    if (tableModel.getRowCount() > 0) {
                        loadAllCrops();
                    }
                    resetSelectedCropId();
                    // Fields should be editable after clearing
                    setFieldsEditable(true);

                    if (isEditing) {
                        isEditing = false;
                        btnUpdate.setText("Update Crop");
                    }

                    // Refresh dashboard if open
                    refreshDashboard();
                } else {
                    JOptionPane.showMessageDialog(this, "Failed to delete crop.", "Error", JOptionPane.ERROR_MESSAGE);
                }
            } catch (Exception e) {
                JOptionPane.showMessageDialog(this, "Error: " + e.getMessage(), "Database Error",
                        JOptionPane.ERROR_MESSAGE);
                e.printStackTrace();
            }
        }
    }//GEN-LAST:event_btnDeleteActionPerformed

    private void btnAddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddActionPerformed
        // TODO add your handling code here:
   // GEN-FIRST:event_btnAddActionPerformed
        // TODO add your handling code here:

        // Get form data - FIXED: Using java.util.Date from JDateChooser
        String cropName = txtCropName.getText().trim();
        java.util.Date plantingDate = jPlantingDate.getDate(); // java.util.Date
        java.util.Date harvestDate = jHarvestDate.getDate(); // java.util.Date
        String yieldText = txtExpectedYield.getText().trim();
        String status = cmbStatus.getSelectedItem().toString().trim();

        // Validation
        if (cropName.isEmpty() || plantingDate == null || harvestDate == null ||
                yieldText.isEmpty() || status.equals("Select Status")) {
            JOptionPane.showMessageDialog(this, "All fields are required!", "Validation Error",
                    JOptionPane.ERROR_MESSAGE);
            return;
        }

        // Validate dates - FIXED: Use .before() for java.util.Date
        if (harvestDate.before(plantingDate)) {
            JOptionPane.showMessageDialog(this, "Harvest date cannot be before planting date!", "Validation Error",
                    JOptionPane.ERROR_MESSAGE);
            return;
        }

        // Validate expected yield
        double expectedYield;
        try {
            expectedYield = Double.parseDouble(yieldText);
            if (expectedYield <= 0) {
                JOptionPane.showMessageDialog(this, "Please enter a valid expected yield!", "Validation Error",
                        JOptionPane.ERROR_MESSAGE);
                return;
            }
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Expected yield must be a number!", "Validation Error",
                    JOptionPane.ERROR_MESSAGE);
            return;
        }

        try {
            // Create crop object
            Crop crop = new Crop();
            crop.setNationalId(SessionManager.getInstance().getCurrentUserId());
            crop.setCropName(cropName);
            crop.setPlantingDate(plantingDate); // java.util.Date
            crop.setHarvestDate(harvestDate); // java.util.Date
            crop.setExpectedYield(expectedYield);
            crop.setStatus(status);

            // Save to database via controller
            CropController cropController = new CropController();
            int result = cropController.createCrop(crop);

            if (result > 0) {
                JOptionPane.showMessageDialog(this, "Crop added successfully!");
                clearForm();
                // Only refresh table if it has data (user clicked Show All)
                if (tableModel.getRowCount() > 0) {
                    loadAllCrops();
                }
                resetSelectedCropId();
                // Fields should be editable after clearing
                setFieldsEditable(true);

                // Notify SessionManager that data changed
                SessionManager.getInstance().notifyDataChanged("crop");
            } else {
                JOptionPane.showMessageDialog(this, "Failed to add crop. Please try again.", "Error", JOptionPane.ERROR_MESSAGE);
            }

        } catch (java.rmi.ConnectException e) {
            JOptionPane.showMessageDialog(this, "Unable to connect to server. Please ensure the server is running and try again.", "Connection Error",
                    JOptionPane.ERROR_MESSAGE);
        } catch (java.rmi.RemoteException e) {
            String msg = e.getMessage();
            if (msg != null && !msg.trim().isEmpty()) {
                JOptionPane.showMessageDialog(this, msg, "Error", JOptionPane.ERROR_MESSAGE);
            } else {
                JOptionPane.showMessageDialog(this, "Connection error. Please check your network connection and try again.", "Network Error",
                        JOptionPane.ERROR_MESSAGE);
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "An error occurred while adding crop. Please try again.", "Error",
                    JOptionPane.ERROR_MESSAGE);
            e.printStackTrace();
        }
    }//GEN-LAST:event_btnAddActionPerformed

    private void btnSearchActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSearchActionPerformed
        // TODO add your handling code here:
     // GEN-FIRST:event_btnSearchActionPerformed
        // TODO add your handling code here:
        String searchTerm = txtCropName.getText().trim();
        if (searchTerm.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please enter a crop name to search.", "Search Error",
                    JOptionPane.WARNING_MESSAGE);
            return;
        }

        try {
            CropController cropController = new CropController();
            List<Crop> searchResults = cropController.searchCropsByName(
                    SessionManager.getInstance().getCurrentUserId(),
                    searchTerm);

            if (searchResults.isEmpty()) {
                JOptionPane.showMessageDialog(this, "No crops found with name: " + searchTerm, "No Results",
                        JOptionPane.INFORMATION_MESSAGE);
                clearForm();
                resetSelectedCropId();
            } else {
                // Display first result in form (non-editable)
                Crop crop = searchResults.get(0);
                populateForm(crop);
                setFieldsEditable(false);
                setSelectedCropId(crop.getCropId());

                // Display only the first result in the table (single-row view)
                java.util.List<Crop> single = new java.util.ArrayList<>();
                single.add(crop);
                displayCropsInTable(single);

                JOptionPane.showMessageDialog(this,
                        "Record loaded. Click Update to modify or Delete to remove.",
                        "Search Results",
                        JOptionPane.INFORMATION_MESSAGE);
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error during search: " + e.getMessage(), "Search Error",
                    JOptionPane.ERROR_MESSAGE);
            e.printStackTrace();
        }
    }//GEN-LAST:event_btnSearchActionPerformed

