    private boolean isFormNotEmpty() {
        return !txtAnimalType.getText().trim().isEmpty() ||
                !txtBreed.getText().trim().isEmpty() ||
                !txtAge.getText().trim().isEmpty() ||
                !txtQuantity.getText().trim().isEmpty() ||
                !cmbStatus.getSelectedItem().toString().equals("Select Health Status");
    }

    // Refresh the main livestock form
    private void refreshLivestockForm() {
        java.awt.Window[] windows = java.awt.Window.getWindows();
        for (java.awt.Window window : windows) {
            if (window instanceof LivestockForm) {
                LivestockForm livestockForm = (LivestockForm) window;
                livestockForm.loadAllLivestock(); // Refresh the table
                break;
            }
        }
    }

    // Refresh dashboard
    private void refreshDashboard() {
        java.awt.Window[] windows = java.awt.Window.getWindows();
        for (java.awt.Window window : windows) {
            if (window instanceof DashboardFrame) {
                DashboardFrame dashboard = (DashboardFrame) window;
                dashboard.loadDashboardData();
                break;
            }
        }
    }

