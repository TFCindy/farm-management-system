    private void btnSaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveActionPerformed
        // TODO add your handling code here:
         // GEN-FIRST:event_btnSaveActionPerformed
        // TODO add your handling code here:
        // TODO add your handling code here:

        // Get form data
        String animalType = txtAnimalType.getText().trim();
        String breed = txtBreed.getText().trim();
        String ageText = txtAge.getText().trim();
        String quantityText = txtQuantity.getText().trim();
        String healthStatus = cmbStatus.getSelectedItem().toString().trim();

        // Validation - All fields except breed are required
        if (animalType.isEmpty() ||
                ageText.isEmpty() ||
                quantityText.isEmpty() ||
                healthStatus.equals("Select Health Status")) {

            JOptionPane.showMessageDialog(this,
                    "Please fill all required fields!\n(Animal Type, Age, Quantity, and Health Status are required)",
                    "Validation Error",
                    JOptionPane.ERROR_MESSAGE);
            return;
        }

        // Validate age is a number and within range
        int age;
        try {
            age = Integer.parseInt(ageText);
            if (age < 0 || age > 50) {
                JOptionPane.showMessageDialog(this,
                        "Please enter a valid age (0-50)!",
                        "Validation Error",
                        JOptionPane.ERROR_MESSAGE);
                return;
            }
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this,
                    "Age must be a number!",
                    "Validation Error",
                    JOptionPane.ERROR_MESSAGE);
            return;
        }

        // Validate quantity is a number and within range
        int quantity;
        try {
            quantity = Integer.parseInt(quantityText);
            if (quantity <= 0) {
                JOptionPane.showMessageDialog(this,
                        "Please enter a valid quantity !",
                        "Validation Error",
                        JOptionPane.ERROR_MESSAGE);
                return;
            }
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this,
                    "Quantity must be a number!",
                    "Validation Error",
                    JOptionPane.ERROR_MESSAGE);
            return;
        }

        try {
            // Check if user is logged in
            SessionManager session = SessionManager.getInstance();
            if (!session.isLoggedIn()) {
                showDualLanguageError("Please login to add livestock.");
                this.dispose();
                return;
            }

            // Create livestock object
            Livestock livestock = new Livestock();
            // Livestock uses User object, not nationalId directly
            User user = new User();
            user.setNationalId(session.getCurrentUserId());
            livestock.setUser(user);
            livestock.setAnimalType(animalType);
            livestock.setBreed(breed.isEmpty() ? "Not specified" : breed); // Handle optional breed
            livestock.setAge(age);
            livestock.setHealthStatus(healthStatus);
            livestock.setQuantity(quantity);

            // Save to database via controller
            LivestockController livestockController = new LivestockController();
            int result = livestockController.createLivestock(livestock);

            if (result > 0) {
                // Notify SessionManager that data changed
                SessionManager.getInstance().notifyDataChanged("livestock");
                
                // Dispose immediately after save
                this.dispose();

            } else {
                showDualLanguageError("Failed to add livestock. Please try again.");
            }

        } catch (java.rmi.ConnectException e) {
            showDualLanguageError("Unable to connect to server. Please ensure the server is running and try again.");
        } catch (java.rmi.RemoteException e) {
            showDualLanguageError("Connection error. Please check your network connection and try again.");
        } catch (Exception e) {
            showDualLanguageError("An error occurred while adding livestock. Please try again.");
        }
    }//GEN-LAST:event_btnSaveActionPerformed

