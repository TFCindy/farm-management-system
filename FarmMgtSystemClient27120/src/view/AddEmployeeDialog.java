    private void btnSaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveActionPerformed
        // TODO add your handling code here:
      // GEN-FIRST:event_jButton1ActionPerformed

        // TODO add your handling code here
        // TODO add your handling code here:

        // Check if all required fields are filled
        if (txtName.getText().trim().isEmpty() ||
                cmbRole.getSelectedItem() == null ||
                txtContact.getText().trim().isEmpty() ||
                txtSalary.getText().trim().isEmpty() ||
                jHireDate.getDate() == null) {
            showDualLanguageError("All fields are required!");
            return;
        }

        // Contact validation - must be exactly 10 digits
        String contact = txtContact.getText().trim();
        if (!contact.matches("\\d{10}")) {
            showDualLanguageError("Contact must be exactly 10 digits!");
            txtContact.requestFocus();
            return;
        }

        // National ID validation - using your existing validation
        String nationalId = currentUser.getNationalId();
        if (nationalId != null && !nationalId.trim().isEmpty()) {
            if (!nationalId.matches("\\d{16}")) {
                showDualLanguageError("Your National ID must be exactly 16 digits!");
                return;
            }

            // Extract digits for checks
            int firstDigit = Character.getNumericValue(nationalId.charAt(0));
            int yearOfBirth = Integer.parseInt(nationalId.substring(1, 5)); // digits 2-5
            int genderDigit = Character.getNumericValue(nationalId.charAt(5));
            int serialNumber = Integer.parseInt(nationalId.substring(6, 13)); // digits 7-13

            // First digit: status (1 = citizen, for example)
            if (firstDigit != 1) {
                showDualLanguageError("Invalid National ID.");
                return;
            }

            // Year of birth: reasonable range (e.g., 1900 to current year)
            int currentYear = java.time.Year.now().getValue();
            if (yearOfBirth < 1900 || yearOfBirth > currentYear) {
                showDualLanguageError("Invalid year of birth in National ID.");
                return;
            }

            // Gender digit: 7 = female, 8 = male
            if (genderDigit != 7 && genderDigit != 8) {
                showDualLanguageError("Invalid National ID.");
                return;
            }

            // Serial number: must be >= 1 (optional, for extra check)
            if (serialNumber < 1) {
                showDualLanguageError("Invalid National ID.");
                return;
            }
        }

        // Salary validation
        try {
            double salary = Double.parseDouble(txtSalary.getText().trim());
            if (salary <= 0) {
                showDualLanguageError("Salary must be a positive number!");
                txtSalary.requestFocus();
                return;
            }

            // Optional: Set maximum salary limit
            if (salary > 1000000) { // 1 million maximum
                showDualLanguageError("Salary cannot exceed 1,000,000!");
                txtSalary.requestFocus();
                return;
            }
        } catch (NumberFormatException e) {
            showDualLanguageError("Salary must be a valid number!");
            txtSalary.requestFocus();
            return;
        }

        // Hire date validation - cannot be in the future
        java.util.Date hireDate = jHireDate.getDate();
        java.util.Date currentDate = new java.util.Date();
        if (hireDate.after(currentDate)) {
            showDualLanguageError("Hire date cannot be in the future!");
            jHireDate.requestFocus();
            return;
        }

        try {
            // Check if user is logged in
            SessionManager session = SessionManager.getInstance();
            if (!session.isLoggedIn()) {
                showDualLanguageError("Please login to add employee.");
                this.dispose();
                return;
            }

            // Create employee object
            Employee employee = new Employee();
            String currentUserNationalId = session.getCurrentUserId();
            employee.setNationalId(currentUserNationalId); // Current user's national ID
            employee.setName(txtName.getText().trim());
            employee.setRole(cmbRole.getSelectedItem().toString());
            employee.setContact(contact);
            employee.setSalary(Double.parseDouble(txtSalary.getText().trim()));
            employee.setHireDate(hireDate);

            // Save to database via controller
            EmployeeController employeeController = new EmployeeController();
            int result = employeeController.createEmployee(employee);

            if (result > 0) {
                // Notify SessionManager that data changed
                SessionManager.getInstance().notifyDataChanged("employee");
                
                // Dispose immediately after save
                this.dispose();

            } else {
                showDualLanguageError("Failed to add employee. Please try again.");
            }

        } catch (NumberFormatException e) {
            showDualLanguageError("Please enter valid numbers for Salary!");
            txtSalary.requestFocus();
        } catch (java.rmi.ConnectException e) {
            showDualLanguageError("Unable to connect to server. Please ensure the server is running and try again.");
        } catch (java.rmi.RemoteException e) {
            showDualLanguageError("Connection error. Please check your network connection and try again.");
        } catch (Exception ex) {
            showDualLanguageError("An error occurred while adding employee. Please try again.");
        }
    }//GEN-LAST:event_btnSaveActionPerformed

